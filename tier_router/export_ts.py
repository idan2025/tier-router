"""Write hooks/model.ts: the questions, keyword rules, model profiles and fitted
weights the plugin uses, generated from classify.py and the weights files so
the plugin and the evaluation can never disagree.

  python3 -m tier_router.export_ts
"""
import json
from pathlib import Path

from . import classify

OUT = Path(__file__).resolve().parent.parent / "hooks" / "model.ts"


def main():
    signals = {name: rx.pattern for name, rx in classify.SIGNALS.items()}
    weights = {f: classify.load_weights(f) for f in classify.PROFILES}
    body = f"""// Generated by tier_router/export_ts.py from classify.py and the weights files.
// Do not edit: change those and run `python3 -m tier_router.export_ts`
// (eval/tune.py --write does it too).

export const QUESTIONS = {json.dumps(classify.QUESTIONS, indent=2)} as const

export const SIGNALS: Record<string, RegExp> = {{
{chr(10).join(f"  {n}: new RegExp({json.dumps(p)}, 'gi')," for n, p in signals.items())}
}}

export const QUICK = new RegExp({json.dumps(classify.QUICK.pattern)}, 'i')

export const POSITIVE = {json.dumps(list(classify.POSITIVE))} as const
export const NEGATIVE = {json.dumps(list(classify.NEGATIVE))} as const

export const PROFILES: Record<string, {{ min_ollama: string; context_chars: number; prompt_chars: number }}> = {json.dumps(classify.PROFILES, indent=2)}

/** Fitted weights per decision-model family; Jev uses tev1's. */
export const WEIGHTS_BY_FAMILY: Record<string, Record<string, number>> = {json.dumps(weights, indent=2)}

export const WEIGHTS: Record<string, number> = WEIGHTS_BY_FAMILY.tev1!
"""
    OUT.write_text(body)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
